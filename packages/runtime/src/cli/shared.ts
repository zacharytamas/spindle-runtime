// A hook always has a time limit. A tool has one only when the operator sets it. The kind is read before the
// operation is redacted, because a secret can be the word that names the kind.
export const holdNote = (threadId: string, operation: string, clean: (text: string) => string, exit: string) =>
  operation.startsWith("tool ")
    ? `${clean(operation)} has not returned. Thread ${threadId} stays held until it returns. Press Ctrl-C twice to ${exit}. Use --tool-timeout to bound tool calls.`
    : `${clean(operation)} has not returned. Thread ${threadId} stays held until it returns or reaches its time limit. Press Ctrl-C twice to ${exit}.`

export const note = (text: string) => Console.error(`spindle: ${text}`)
export const describe = (error: unknown) => (error instanceof Error ? error.message : String(error))
export const plural = (count: number, word: string) => `${count} ${word}${count === 1 ? "" : "s"}`
export const toolCallLine = (call: ProviderToolCallPart) => `[tool call] ${call.name} ${JSON.stringify(call.arguments)}`
export const requestText = ({ signal: _, ...request }: ProviderRequest) => JSON.stringify(request, null, 2)

export class CommandFailed extends Data.TaggedError("CommandFailed") {
  override readonly [Runtime.errorReported] = false
}

export const fail = (message: string, print = note) => Effect.andThen(print(message), new CommandFailed())

export const commandErrors =
  (identify = note) =>
  <A, E, R>(effect: Effect.Effect<A, E, R>) =>
    Effect.catchCause(effect, (cause): Effect.Effect<never, E | CommandFailed> => {
      const error = Cause.squash(cause)
      if (error instanceof CommandFailed || Cause.hasInterruptsOnly(cause)) return Effect.failCause(cause)
      return error instanceof ThreadTerminated ? fail(error.message, identify) : fail(describe(error))
    })

interface Output {
  secrets: Set<string>
  clean: (text: string) => string
  identify: typeof note
}

export const withOutput = <A, E, R>(body: (output: Output) => Effect.Effect<A, E, R>, escapeText = (s: string) => s) =>
  Console.consoleWith((current) => {
    const secrets = new Set<string>()
    const redact = redactor(secrets)
    const clean = (text: string) => escapeText(redact(text))
    const parts = (args: ReadonlyArray<unknown>) => args.map((part) => (typeof part === "string" ? clean(part) : part))
    const console: Console.Console = Object.assign(Object.create(current), {
      log: (...args: ReadonlyArray<unknown>) => current.log(...parts(args)),
      error: (...args: ReadonlyArray<unknown>) => current.error(...parts(args)),
    })
    // Identifiers generated by the runtime must survive even a one-character secret.
    const identify = (text: string) => Effect.sync(() => current.error(`spindle: ${text}`))
    const logger = Logger.make(({ message }) =>
      console.error(`spindle: ${Array.isArray(message) ? message.join(" ") : message}`),
    )
    return body({ secrets, clean, identify }).pipe(
      commandErrors(identify),
      Effect.provide(Logger.layer([logger])),
      Effect.provideService(Console.Console, console),
    )
  })

const loadScript = (file: string) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem
    const text = yield* fs
      .readFileString(file)
      .pipe(Effect.catch((error) => fail(`cannot read the script ${file}: ${error.message}`)))
    const script = yield* decodeScript(text).pipe(
      Effect.catch((error) => fail(`${file} is not a valid script: ${error.message.replaceAll(/\s*\n\s*/g, " ")}`)),
    )
    return scriptedProvider(script)
  })

// SQLite says only that it cannot open the file, so the command names a missing directory or a directory first.
export const openDatabase = (filename: string) =>
  Layer.unwrap(
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem
      const path = yield* Path.Path
      const problem = (cause: string) => fail(`cannot open the database ${filename}: ${cause}`)
      if (filename !== ":memory:") {
        const info = yield* Effect.option(fs.stat(filename))
        if (Option.isSome(info) && info.value.type === "Directory") return yield* problem("it is a directory")
        const directory = path.dirname(filename)
        if (!(yield* fs.exists(directory))) return yield* problem(`the directory ${directory} does not exist`)
      }
      return Layer.provide(sqliteStore, SqliteLive({ filename })).pipe(
        Layer.catchTag("SqlError", (error) =>
          Layer.effectContext<Stores, CommandFailed, never>(
            problem(error.cause.cause instanceof Error ? error.cause.cause.message : error.message),
          ),
        ),
      )
    }),
  )

export const loadTimeoutFlag = Flag.Finite("load-timeout").pipe(
  Flag.filter(
    (seconds) => seconds > 0,
    () => "--load-timeout takes a number of seconds above 0",
  ),
  Flag.withDescription("Seconds one definition file or package loader may take. The default is 30."),
  Flag.withDefault(30),
)

export const commandRegistry = (root: string, seconds: number) =>
  Layer.effect(
    Registry,
    isolateDefinitionLoads(seconds, Effect.provide(Registry, Registry.layer(root)), describeCause).pipe(
      Effect.map(({ value, faults }) => ({
        ...value,
        issues: [
          ...value.issues,
          ...faults.map(({ file, reason }) => issue("definition_load_failed", file, "", reason)),
        ],
      })),
    ),
  )

